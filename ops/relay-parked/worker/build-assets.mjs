// Builds the fixed browser files into src/assets.generated.js, which the Worker
// serves. The output is committed and deterministic, so anyone can rebuild it
// and compare hashes with what the relay really serves (docs/RELAY_PRIVACY.md).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const require = createRequire(join(root, 'package.json'));
const { build } = require('esbuild');

async function bundle(entry, format) {
  const out = await build({ entryPoints: [join(root, 'packages/tunnel/src', entry)], bundle: true, format, target: 'es2022', minify: true, write: false, legalComments: 'none', absWorkingDir: root });
  return out.outputFiles[0].text;
}

const files = {
  '/__josi/loader.html': { type: 'text/html; charset=utf-8', body: readFileSync(join(here, 'loader/loader.html'), 'utf8') },
  '/__josi/privacy.html': { type: 'text/html; charset=utf-8', body: readFileSync(join(here, 'loader/privacy.html'), 'utf8') },
  '/__josi/loader.css': { type: 'text/css; charset=utf-8', body: readFileSync(join(here, 'loader/loader.css'), 'utf8') },
  '/__josi/loader.js': { type: 'text/javascript; charset=utf-8', body: await bundle('browserLoader.ts', 'esm') },
  '/__josi/sw.js': { type: 'text/javascript; charset=utf-8', body: await bundle('browserWorker.ts', 'iife') },
};

const hashes = Object.fromEntries(Object.entries(files).map(([path, file]) => [path, createHash('sha256').update(file.body).digest('hex')]));
writeFileSync(join(here, 'src/assets.generated.js'), `// Generated by build-assets.mjs. Do not edit.\nexport const ASSETS = ${JSON.stringify(files)};\nexport const ASSET_HASHES = ${JSON.stringify(hashes, null, 2)};\n`);
console.log(hashes);
